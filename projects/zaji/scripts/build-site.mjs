function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function toArray(value) {
  if (Array.isArray(value)) return value.map(String).map((item) => item.trim()).filter(Boolean);
  return value ? [String(value).trim()] : [];
}

function validateDate(value, label) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) throw new Error(`${label} must use YYYY-MM-DD`);
  const [year, month, day] = value.split("-").map(Number);
  const date = new Date(Date.UTC(year, month - 1, day));
  if (date.getUTCFullYear() !== year || date.getUTCMonth() !== month - 1 || date.getUTCDate() !== day) {
    throw new Error(`${label} is not a real calendar date`);
  }
}

function formatDate(value, style = "short") {
  const [year, month, day] = value.split("-").map(Number);
  if (style === "year") return String(year);
  if (style === "month-day") return `${String(month).padStart(2, "0")}—${String(day).padStart(2, "0")}`;
  if (style === "long") return `${year} 年 ${month} 月 ${day} 日`;
  return `${year}.${String(month).padStart(2, "0")}.${String(day).padStart(2, "0")}`;
}

function readCollection(type) {
  const dir = resolve(contentDir, type);
  const files = readdirSync(dir)
    .filter((name) => extname(name) === ".md")
    .sort((a, b) => a.localeCompare(b));
  const seenSlugs = new Set();

  return files.map((fileName) => {
    const slug = basename(fileName, ".md");
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) throw new Error(`${fileName}: invalid slug`);
    if (seenSlugs.has(slug)) throw new Error(`${fileName}: duplicate slug ${slug}`);
    seenSlugs.add(slug);

    const source = readFileSync(resolve(dir, fileName), "utf8");
    const { frontmatter, body } = parseFrontmatter(source);
    for (const field of ["title", "date", "summary"]) {
      if (!String(frontmatter[field] ?? "").trim()) throw new Error(`${fileName}: missing ${field}`);
    }
    if (/^#\s+/m.test(body)) throw new Error(`${fileName}: body headings must start at ##`);
    if (!body.trim()) throw new Error(`${fileName}: body must not be empty`);
    validateDate(frontmatter.date, `${fileName}: date`);
    if (frontmatter.updated) validateDate(frontmatter.updated, `${fileName}: updated`);

    const record = {
      type,
      slug,
      title: frontmatter.title.trim(),
      date: frontmatter.date,
      updated: frontmatter.updated?.trim() || "",
      summary: frontmatter.summary.trim(),
      tags: toArray(frontmatter.tags),
      body: body.trim(),
      relatedWorks: toArray(frontmatter.related_works),
      relatedPosts: toArray(frontmatter.related_posts),
      companionPosts: toArray(frontmatter.companion_posts),
      status: frontmatter.status?.trim() || "",
      artifactType: frontmatter.type?.trim() || "",
      cover: frontmatter.cover?.trim() || "",
      coverAlt: frontmatter.cover_alt?.trim() || "",
      liveUrl: frontmatter.live_url?.trim() || "",
      sourceUrl: frontmatter.source_url?.trim() || "",
    };

    if (type === "works") {
      for (const field of ["status", "artifactType", "cover", "coverAlt", "liveUrl", "sourceUrl"]) {
        if (!record[field]) throw new Error(`${fileName}: missing ${field}`);
      }
      if (!/^assets\/[a-z0-9][a-z0-9._/-]*$/i.test(record.cover) || record.cover.includes("..")) {
        throw new Error(`${fileName}: cover must be a site-root assets/ path`);
      }
      if (!existsSync(resolve(projectDir, record.cover))) throw new Error(`${fileName}: cover does not exist: ${record.cover}`);
    }

    const plainText = renderMarkdown(record.body).text;
    record.readingMinutes = Math.max(1, Math.ceil(plainText.length / 500));
    return record;
  }).sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));
}

function assertRelations(blogs, works) {
  const blogSlugs = new Set(blogs.map((item) => item.slug));
  const workSlugs = new Set(works.map((item) => item.slug));
  for (const blog of blogs) {
    for (const slug of blog.relatedWorks) {
      if (!workSlugs.has(slug)) throw new Error(`${blog.slug}: unknown related work ${slug}`);
    }
    for (const slug of blog.companionPosts) {
      if (!blogSlugs.has(slug)) throw new Error(`${blog.slug}: unknown companion post ${slug}`);
      if (slug === blog.slug) throw new Error(`${blog.slug}: companion post cannot reference itself`);
    }
  }
  for (const work of works) {
    for (const slug of work.relatedPosts) {
      if (!blogSlugs.has(slug)) throw new Error(`${work.slug}: unknown related post ${slug}`);
    }
  }
}

function resolveSiteHref(value, siteRoot) {
  if (/^(?:https?:\/\/|mailto:|#|\/)/i.test(value)) return value;
  return `${siteRoot}/${value}`;
}

function renderTags(tags) {
  if (tags.length === 0) return "";
  return `<ul class="tag-list" aria-label="标签">${tags.map((tag) => `<li>${escapeHtml(tag)}</li>`).join("")}</ul>`;
}


function groupBlogsByYear(blogs) {
  const groups = new Map();
  for (const blog of blogs) {
    const year = formatDate(blog.date, "year");
    if (!groups.has(year)) groups.set(year, []);
    groups.get(year).push(blog);
  }
  return groups;
}


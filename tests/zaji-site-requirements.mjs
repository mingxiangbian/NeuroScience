const generatedPages = [homeUrl, blogIndexUrl, worksIndexUrl];
for (const file of blogFiles) generatedPages.push(new URL(`blog/${file.replace(/\.md$/, "")}/index.html`, projectUrl));
for (const file of workFiles) generatedPages.push(new URL(`works/${file.replace(/\.md$/, "")}/index.html`, projectUrl));
for (const pageUrl of generatedPages) {
  assert.equal(existsSync(pageUrl), true, `${pageUrl.pathname} should be generated`);
  const html = readFileSync(pageUrl, "utf8");
  assert.ok(html.includes(generatedMarker), `${pageUrl.pathname} should identify generated output`);
  assert.equal((html.match(/<h1(?:\s|>)/g) ?? []).length, 1, `${pageUrl.pathname} should contain exactly one h1`);
  assert.match(html, /<html lang="zh-CN">/, `${pageUrl.pathname} should use Chinese document language`);
  assert.match(html, /class="site-nav" aria-label="主导航"/, `${pageUrl.pathname} should include the shared semantic navigation`);
  assert.doesNotMatch(html, /\bfetch\s*\(/, `${pageUrl.pathname} should contain its content without client-side data fetching`);
  for (const match of html.matchAll(/\b(?:href|src)="([^"]+)"/g)) {
    const target = match[1];
    if (/^(?:https?:|mailto:|data:|#|\/)/i.test(target)) continue;
    const resolved = new URL(target, pageUrl);
    resolved.hash = "";
    resolved.search = "";
    assert.equal(existsSync(resolved), true, `${pageUrl.pathname} should not reference missing local target ${target}`);
  }
}

